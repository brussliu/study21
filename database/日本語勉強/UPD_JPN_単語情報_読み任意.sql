-- 経緯:
--   新規登録画面は見出し語だけを受け取る（読みは AI から取る）方針なのに、
--   表が「読み」を必須にしていたため、**330 語すべてが CHECK で弾かれた**。
--   2.0（STY_日本語単語母表）は読みが NOT NULL で、画面も読みを入力させていたが、
--   2.1 は「先に見出し語だけ入れて、読みは AI 取得で後から埋める」流れにする。
--
-- 変えるもの:
--   1. 読み            … NOT NULL を外す（NULL = まだ読みが無い）
--   2. CK_JPN_単語_見出し語 … 読み と 読みキー の必須を外す（見出し語と見出し語キーだけ必須）
--   3. uq_jpn_word_key  … 「読みキーが空の語」を複数入れられるように部分一意索引へ替える
--      （同じ見出し語でも、読みが分かれば別の語。読みが未取得の間は重複を許す）
--   4. 読みキー        … NOT NULL のまま（空文字は「まだ読みが無い」を表す）。
--      NULL にすると部分索引の条件が 2 通りになり、検索の当たり方が変わってしまうため。
--
-- アプリ側で必要なこと:
--   ・`POST /words` は読みが空なら 読み を NULL、読みキー を '' で入れる
--   ・一覧・詳細は 読み が NULL のとき「—」を出す（画面は既に NULL を許容している）
--   ・AI 詳細取得（batC41）が成功したら、詳細JSON の pronunciations から 読み を埋める
--     （**この後埋める処理はまだ実装していない**。設計 §5 に残す）
--
-- 冪等: 制約・索引は DROP IF EXISTS してから作り直す。
-- 対象DB: study21 (PostgreSQL)
-- ============================================================================

-- 1. 読みを任意にする
ALTER TABLE public."JPN_単語情報" ALTER COLUMN "読み" DROP NOT NULL;

-- 2. 見出し語（と検索キー）だけを必須にする
ALTER TABLE public."JPN_単語情報" DROP CONSTRAINT IF EXISTS "CK_JPN_単語_見出し語";
ALTER TABLE public."JPN_単語情報"
    ADD CONSTRAINT "CK_JPN_単語_見出し語"
        CHECK (
            NULLIF(BTRIM("見出し語"), '') IS NOT NULL
            AND NULLIF(BTRIM("見出し語キー"), '') IS NOT NULL
            AND "読みキー" IS NOT NULL
        );

-- 3. 読みが未取得の間は、同じ見出し語を重複して入れられるようにする
DROP INDEX IF EXISTS public.uq_jpn_word_key;
CREATE UNIQUE INDEX IF NOT EXISTS uq_jpn_word_key
    ON public."JPN_単語情報" ("見出し語キー", "読みキー")
    WHERE NULLIF(BTRIM("読みキー"), '') IS NOT NULL;

COMMENT ON COLUMN public."JPN_単語情報"."読み" IS
    '読み。**未取得の間は NULL**（新規登録では入れず、AI 詳細取得で後から埋める）';
COMMENT ON COLUMN public."JPN_単語情報"."読みキー" IS
    '読みの検索キー。まだ読みが無い語は空文字（その間は (見出し語キー, 読みキー) の一意を課さない）';
