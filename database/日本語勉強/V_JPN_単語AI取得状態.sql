-- Study 2.1  日本語勉強 DDL 追加
-- 内容: 単語ごとの「AI 取得の状態」を引くビュー
-- テーブル: public."v_jpn_word_ai_state"（VIEW）
-- ----------------------------------------------------------------------------
-- なぜ:
--   単語情報管理の一覧には「取得状態（A・B，C，D，E）」の列があるが、
--   AI の実行記録は JPN_AI生成履歴情報 にしか無いので、一覧 API が状態を返せず
--   画面は常に「未取得」を出していた（設計のレビュー A4）。
--
-- 見せ方（1 行 = 1 語 × 1 内容種別）:
--   ・"状態コード"  … 一番新しい実行の状態（登録日時 → 生成ID の降順）
--   ・"成功あり"    … その語・その内容種別で **一度でも SUCCEEDED になったか**
--   一覧は「成功あり」を優先して「取得済」を出し、無ければ最新の状態（失敗／取得中）を出す。
--   一度成功した内容は DB に残っている（詳細は UPSERT、問題は ARCHIVED で保持）ので、
--   あとで失敗しても「取得済」のままにするほうが実態に合う。
--
-- 対象DB: study21 (PostgreSQL)
-- ============================================================================

BEGIN;

-- 列を足すときは CREATE OR REPLACE では順番を変えられないので作り直す
-- （このビューを参照する DB オブジェクトは無い）
DROP VIEW IF EXISTS public."v_jpn_word_ai_state";

CREATE VIEW public."v_jpn_word_ai_state" AS
SELECT DISTINCT ON (g."単語ID", g."内容種別コード")
       g."単語ID",
       g."内容種別コード",
       g."状態コード",
       bool_or(g."状態コード" = 'SUCCEEDED')
           OVER (PARTITION BY g."単語ID", g."内容種別コード") AS "成功あり",
       g."生成件数",
       g."失敗件数",
       g."エラーコード",
       g."AI区分",
       g."モデル名",
       g."登録日時",
       g."更新日時"
  FROM public."JPN_AI生成履歴情報" AS g
 ORDER BY g."単語ID", g."内容種別コード", g."登録日時" DESC, g."生成ID" DESC;

COMMENT ON VIEW public."v_jpn_word_ai_state" IS
    '単語 × 内容種別ごとの AI 生成状態（最新 1 行）と、一度でも成功したか（成功あり）。一覧の「取得状態」列が使う';

COMMIT;

-- 確認: ビューの中身（実行がまだ無ければ 0 件）
SELECT g."単語ID", g."内容種別コード", g."状態コード", g."成功あり"
  FROM public."v_jpn_word_ai_state" AS g
 ORDER BY g."単語ID", g."内容種別コード"
 LIMIT 10;
