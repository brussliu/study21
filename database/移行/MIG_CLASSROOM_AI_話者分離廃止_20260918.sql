-- 授業録音: 「話者分離」設定の廃止（2026-09-18）
--
-- 話者は**音源**で決めるようにした（マイク＝学生／共有の音＝先生／マイクのみ＝講義）ため、
-- 「話者分離」の設定は意味を持たなくなった（保存するだけで何もしない値だった）。
--
-- 消すもの（順序が大事。COM_設定情報 → COM_設定項目 の外部キーがあるため）:
--   1. COM_設定情報 … 保存されていた値（'none' / 'two_speaker'）。**保存するだけで何も
--      しない値**だったので、消しても失う情報は無い（音源で話者を決めるようにした）。
--   2. COM_設定項目 … 設定ページのカタログ（画面の項目定義からも外した）
-- 旧データの互換: 値が残っていても壊れないようにアプリ側は読まない（この移行で消える）。
--
-- 適用のタイミング: **新バージョン（画面と API）を配備したあと**に流す。
--   いま配備されている旧画面は「話者分離」を保存リクエストに含めるため、カタログ行を先に消すと
--   外部キー（FK_COM_設定情報_項目）に違反して**設定の保存そのものが失敗**する（実測）。
--   アプリは値が無くても 'none' として動くので、値の削除は先に流しても安全。
--
-- 適用: 一度だけ流す（再実行しても壊れない）。
-- =====================================================================

DELETE FROM public."COM_設定情報"
 WHERE "ページ区分" = 'CLASSROOM_AI'
   AND "設定キー" = 'CLASSROOM_AI_DIARIZATION';

DELETE FROM public."COM_設定項目"
 WHERE "ページ区分" = 'CLASSROOM_AI'
   AND "設定キー" = 'CLASSROOM_AI_DIARIZATION';
