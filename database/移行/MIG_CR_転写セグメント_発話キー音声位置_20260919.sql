-- ============================================================================
-- 授業録音: 転写セグメントの「発話キー」の作り方を、音声の位置（音源#開始ミリ秒）に変える
-- ----------------------------------------------------------------------------
-- 背景（2026-09-19 改修）:
--   発話キーは「音源 + 認識セッション番号 + 阿里雲の sentence_id」（例 'mic#2#17'）だった。
--   セッション番号は**音源がつなぎ直すたびに増える**ので、同じ発話でも
--     * 断線して張り直したあと（同じ音を送り直したとき）
--     * 後端（user-api）を再起動したあと
--   に**別のキー**が付き、同じ音が 2 行になった。逆に、遅れて届いた重複が
--   **別の古い行を上書き**することもあった（キーが衝突する作りだったため）。
--
-- 新しい作り方（アプリ側・ClassroomSttStreamService）: 音源 + 開始ミリ秒（音声の位置）
--   例: 'mic#10000' / 'shared#500'
--   音声の位置は「その音源へこれまでに送ったサンプル数 + 阿里雲の begin_time」で決まり、
--   認識セッションを作り直しても・プロセスを入れ替えても**同じ発話には同じ値**が出る。
--   常時接続（WebSocket）は 100ms（3200 バイト）固定なので、画面が断線復帰で送る
--   `{"type":"resume","from":N}` の番号から位置を戻せる（再起動後もキーが変わらない）。
--
-- この移行でやること:
--   列・索引の**構造は変えない**（"発話キー" VARCHAR(160) と
--   UK_CR_転写セグメント_発話キー はそのまま使える）。DB のコメントだけを実態に合わせる。
--   ※ 既存行の値（'mic#1#1' のような旧形式）は**そのまま残す**。旧形式は区切りが 3 つ、
--      新形式は 2 つなので衝突しない（新形式のキーが旧行を上書きすることはない）。
--      過去の文を新しいキーへ書き換える必要は無い（再送は来ないため）。
--
-- 対象DB: study21 (PostgreSQL)
-- 実行順序: 何度流しても同じ（COMMENT は同じ値で上書きされるだけ）
-- ============================================================================

COMMENT ON COLUMN public."CR_授業転写セグメント情報"."発話キー" IS
    '発話の安定した識別子（音源#開始ミリ秒＝音声の位置）。同じ発話の再保存は UPDATE にする'
    '（認識セッション番号は使わない＝張り直し・再起動でキーが変わらない）';
