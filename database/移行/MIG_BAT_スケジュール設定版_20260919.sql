-- ============================================================================
-- 移行: BAT_スケジュール状態情報 に「設定版」（実行設定の計画バージョン）を追加する
-- 対象DB: study21 (PostgreSQL)
-- 冪等: ADD COLUMN IF NOT EXISTS / 既存行は 0（＝まだ計画バージョンを記録していない）
-- ----------------------------------------------------------------------------
-- なぜ必要か:
--   実行設定（実行時刻・間隔・ずらし・有効／無効）を変えたとき、
--   「その設定が効き始めた時刻（設定適用日時）」を**設定値の保存と同じトランザクション**で
--   書くようにした。そのとき一緒に進める版がこの列。
--   ・保存がロールバックすれば、設定値も適用日時も版も一緒に戻る（食い違いを作らない）
--   ・再起動後は「いま読んだ設定が保存時の版と同じか」をこの値で判定できる
--     （アプリ以外の経路で DB を直接書き換えた場合は版が進まないので、
--       「適用時刻が記録されていない変更」として安全側に倒せる）
-- 実行順序: database/バッチ/TBL_BAT_スケジュール状態情報.sql の後
-- ============================================================================

ALTER TABLE public."BAT_スケジュール状態情報"
    ADD COLUMN IF NOT EXISTS "設定版" BIGINT NOT NULL DEFAULT 0;

COMMENT ON COLUMN public."BAT_スケジュール状態情報"."設定版" IS
    '実行設定の計画バージョン（設定値の保存と同じトランザクションで 1 つ進める）';
