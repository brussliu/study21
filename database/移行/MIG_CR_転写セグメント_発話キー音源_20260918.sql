-- ============================================================================
-- 授業録音: 転写セグメントに「発話キー」と「音源」を足す（2026-09-18）
-- ----------------------------------------------------------------------------
-- 何のためか:
--   1. 音源で話者を決める（マイク＝学生／共有の音＝先生／マイクのみ＝講義）ので、
--      どの音源から出た文かを DB に残す。
--   2. 認識セッションを作り直しても**同じ文を二度保存しない**ための安定した識別子を持つ。
--      いまは (授業記録ID, 連番) が一意で、連番は STT セッションごとに 1 から振られるため、
--      セッションを張り直すと**一意制約に衝突**する（実測で起きる）。
--
-- 発話キーの作り方（アプリ側）: 音源 + 認識セッション番号 + 阿里雲の sentence_id
--   例: 'mic#2#17' / 'shared#1#4'
--   → セッションを作り直しても衝突せず、同じ文の再送は同じキーになる（＝更新にできる）。
--   ※ 阿里雲の sentence_id はセッション内で 1 から振られるので、セッション番号と組にする。
--
-- 連番の意味は変えない（記録内で 1 から増える表示順。既存データはそのまま）。
-- 並べ替えは「開始オフセット秒 → 連番」で行う（同着は連番で安定させる）。
--
-- 対象DB: study21 (PostgreSQL)
-- 実行順序: 何度流しても同じ（IF NOT EXISTS）
-- ============================================================================

ALTER TABLE public."CR_授業転写セグメント情報"
    ADD COLUMN IF NOT EXISTS "発話キー" VARCHAR(160) NULL,
    ADD COLUMN IF NOT EXISTS "音源"     VARCHAR(20)  NULL;

-- 同じ発話の再送・再保存を 1 行に寄せる（NULL の行＝旧データは対象外）
CREATE UNIQUE INDEX IF NOT EXISTS "UK_CR_転写セグメント_発話キー"
    ON public."CR_授業転写セグメント情報" ("授業記録ID", "発話キー")
    WHERE "発話キー" IS NOT NULL;

COMMENT ON COLUMN public."CR_授業転写セグメント情報"."発話キー" IS
    '発話の安定した識別子（音源#認識セッション番号#sentence_id）。同じ発話の再保存は UPDATE にする';
COMMENT ON COLUMN public."CR_授業転写セグメント情報"."音源" IS
    'この文を出した音源。mic=マイク（学生）/ shared=共有した音（先生）。旧データは NULL（＝講義）';
COMMENT ON COLUMN public."CR_授業転写セグメント情報"."連番" IS
    '記録内の表示順（1 から）。並べ替えは「開始オフセット秒 → 連番」で行う';
