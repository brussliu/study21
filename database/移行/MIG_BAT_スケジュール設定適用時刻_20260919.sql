-- ============================================================================
-- Study 2.1  バッチの実行設定に「適用時刻」を追加
-- ----------------------------------------------------------------------------
-- 背景（利用者の指摘）:
--   実行時刻・実行間隔を変えた直後に、**過去の計画実行点**が実行されてしまう。
--   例: 22:00 に「インターネット利用終了 23:30 → 21:00」と変えると、その場で 21:00 の点が
--   到来済みと見なされ、**すぐにネットが止まる**。
--
-- やること:
--   BAT_スケジュール状態情報 に 設定適用日時 を足す。設定を変えた時刻を保存し、
--   スケジューラは**この時刻より後の計画実行点だけ**を実行する。
--   サービス再起動のときはこの値を引き継ぐので、「利用者の設定変更」と
--   「再起動後の補執行」を区別できる（再起動では適用時刻を進めない）。
--
-- 冪等: ADD COLUMN IF NOT EXISTS（既に在れば何もしない）。
-- 対象DB: study21 (PostgreSQL)
-- ============================================================================

BEGIN;

ALTER TABLE public."BAT_スケジュール状態情報"
    ADD COLUMN IF NOT EXISTS "設定適用日時" TIMESTAMP NULL;

COMMENT ON COLUMN public."BAT_スケジュール状態情報"."設定適用日時" IS
    'いまの実行設定が効き始めた時刻（Asia/Tokyo）。この時刻以前の計画実行点は実行しない';

COMMIT;

\echo '--- 確認: 設定適用日時 列（NULL 可）---'
SELECT column_name, data_type, is_nullable
  FROM information_schema.columns
 WHERE table_schema = 'public' AND table_name = 'BAT_スケジュール状態情報'
   AND column_name = '設定適用日時';
