-- Study 2.1  移行: AI 画図助手の System Prompt を「追加のみ」に合わせる
-- 設定: GEOMETRY_AI / GEOMETRY_AI_ASSIST_SYSTEM_PROMPT
-- ----------------------------------------------------------------------------
-- 背景（利用者の指示）:
--   作図画面から「変更案の反映方法（追加／作図全体を作り直す）」の選択を外し、
--   **AI 画図助手の反映はいつも「いまの作図に追加」**にした（作り直したいときは利用者が
--   【全消去】してから指示する）。依頼（GEO_AI画図指示情報.反映方法）も新しいものは
--   APPEND だけになる（既存の履歴の値はそのまま残す）。
--
--   AI には「いまの作図を踏まえて、追加・変更するコマンドだけを返す」ことをこれまでも
--   伝えていたが、**作図が空のとき**の指示が無かったので、次の 2 点を明記する:
--     1. 既にあるオブジェクトは作り直さない（返すのは今回の指示に必要な**追加・変更**だけ）
--     2. 作図が空（オブジェクトが「（まだありません）」）のときは、必要なものを全部作る
--
-- 何度流しても同じ（同じ値を入れるだけ）。
--
-- 対象DB: study21 (PostgreSQL)
-- 実行順序: database/設定/TBL_COM_設定情報_init.sql の後
-- ============================================================================

BEGIN;

UPDATE public."COM_設定情報"
   SET "設定値" = 'あなたは GeoGebra の作図を日本語の指示で直すアシスタントです。
いま作図されているオブジェクトを踏まえ、指示を実現するために追加・変更するコマンドだけを出力します（既にあるコマンドは繰り返さない）。
いまの作図に既にあるオブジェクトは、作り直すコマンドを返さないでください（消して全部作り直すのではなく、必要な追加・変更だけを返す）。
いまの作図が空のとき（オブジェクトが「（まだありません）」のとき）は、指示に必要なオブジェクトを最初から全部作ってください。
返答の形式は、このプロンプトの末尾に自動で付く「出力形式（JSON Schema）」に従う（説明は「説明」の項目に日本語で 1 文）。
禁止: Delete / File / Import / Export / Execute / SetValue / Button / Checkbox / InputBox / SetActiveView / RunClickScript、スクリプト、外部 URL の読み込み。'
 WHERE "ページ区分" = 'GEOMETRY_AI' AND "設定キー" = 'GEOMETRY_AI_ASSIST_SYSTEM_PROMPT' AND "スコープ" = 'GLOBAL';

UPDATE public."COM_設定項目"
   SET "説明" = 'AI画図助手：System Prompt（いまの作図を踏まえて、追加・変更するコマンドだけを返させる。作図全体の作り直しはさせない）'
 WHERE "ページ区分" = 'GEOMETRY_AI' AND "設定キー" = 'GEOMETRY_AI_ASSIST_SYSTEM_PROMPT';

-- 反映方法の列は**記録用**になり、新しい依頼は APPEND だけになる（既存の履歴の値は変えない）。
COMMENT ON COLUMN public."GEO_AI画図指示情報"."反映区分" IS
    '記録用の反映方法。APPEND=今の作図に追加（**いまは新しい依頼はこれだけ**）/ REPLACE=作図全体を作り直す（過去の履歴の表示・互換のためだけに残る）';

COMMIT;

