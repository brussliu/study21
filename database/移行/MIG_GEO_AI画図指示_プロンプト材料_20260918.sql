-- ============================================================================
-- Study 2.1  移行: AI 画図助手が AI へ渡す材料を増やす
-- テーブル: GEO_AI画図指示情報
-- ----------------------------------------------------------------------------
-- 背景（実測した失敗の分析から）:
--   1. AI には**オブジェクト名だけ**を渡していた。XML にはコマンドで作った図形の定義が
--      残らないことがあり（実測: 円は type="conic" と行列だけで中心・半径が読めない）、
--      AI は「c は円らしい」と推測するしかなかった。→ 画面が applet から取れる
--      **「名前 = 定義（型）」の一覧**を渡す（列 "作図オブジェクト"）。
--   2. AI の案が GeoGebra に拒否されても、その事実は AI に伝わらず**その場で終わっていた**
--      （実測: `Polygon(A, B, C, 3)` が引数の数の間違いで失敗）。→ 画面が同じ指示を
--      **実行できなかった行と理由つき**でもう一度送り、AI に 1 回だけ直させる
--      （列 "失敗の内容"）。
--
-- 何度流しても同じ（ADD COLUMN IF NOT EXISTS / COMMENT ON は上書き）。
--
-- 対象DB: study21 (PostgreSQL)
-- 実行順序: database/図形管理/TBL_GEO_AI画図指示情報.sql の後
-- ============================================================================

ALTER TABLE public."GEO_AI画図指示情報"
    ADD COLUMN IF NOT EXISTS "作図オブジェクト" TEXT NULL,
    ADD COLUMN IF NOT EXISTS "失敗の内容"       TEXT NULL;

COMMENT ON COLUMN public."GEO_AI画図指示情報"."作図オブジェクト" IS
    '指示時点のオブジェクト一覧（「名前 = 定義（型）」の改行区切り）。AI のプロンプト {objects} に使う（空なら XML のラベルで代用）';

COMMENT ON COLUMN public."GEO_AI画図指示情報"."失敗の内容" IS
    '前の案が実行できなかった内容（実行できなかった行と理由）。自動修正のとき AI のプロンプト {failure} に使う';

