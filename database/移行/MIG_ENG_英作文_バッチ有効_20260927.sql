-- ============================================================================
-- Study 2.1  英作文AI添削の 2 バッチを有効にする
-- ----------------------------------------------------------------------------
-- batC11（画像分類・OCR・主題タイトル生成）/ batC12（英検基準AI添削）を
-- `BAT_バッチコントロール情報` に **状態 '1'（有効）** で登録する。
--
-- なぜ必要か:
--   有効／無効の唯一の正は `BAT_バッチコントロール情報`（`database/バッチ/BAT_バッチ管理設計.md`）。
--   行が無いときは定義（`BatchTaskRegistry`）の既定に従い、英作文の 2 バッチは **既定が無効**。
--   そのままだと添削の受付が「バッチが無効に設定されています: batC12」で拒否される。
--   使うバッチは行を作って有効にする（`MIG_GEO_AI作図モードと結果種別_20260918.sql` が
--   batC51-A〜D に対して同じことをしている）。
--
-- 無効にしたいときは **バッチ一覧のスイッチ**で '0' にする（このファイルは再実行しても
-- 既にある行を触らない = ON CONFLICT DO NOTHING。だから人の設定を上書きしない）。
--
-- 実行例:
--   psql -h 192.168.0.100 -p 54320 -U postgres -d study21 -v ON_ERROR_STOP=1 \
--        -f database/移行/MIG_ENG_英作文_バッチ有効_20260927.sql
-- ============================================================================

INSERT INTO public."BAT_バッチコントロール情報" (
    "バッチコード", "状態", "備考", "登録元コード", "更新元コード")
VALUES
    ('batC11', '1', '英作文AI添削（OCR・主題タイトル）。2026-09-27 実装に伴い有効化', 'MIGRATION', NULL),
    ('batC12', '1', '英作文AI添削（英検基準AI添削・非同期）。2026-09-27 実装に伴い有効化', 'MIGRATION', NULL)
ON CONFLICT ("バッチコード") DO NOTHING;

-- 確認
DO $$
DECLARE rows integer;
BEGIN
    SELECT count(*) INTO rows FROM public."BAT_バッチコントロール情報"
     WHERE "バッチコード" IN ('batC11', 'batC12') AND "状態" = '1';
    IF rows = 2 THEN
        RAISE NOTICE 'batC11 / batC12 は有効です（バッチ一覧で切り替えられます）';
    ELSE
        RAISE NOTICE 'batC11 / batC12 のうち % 件だけが有効です（バッチ一覧を確認してください）', rows;
    END IF;
END $$;
