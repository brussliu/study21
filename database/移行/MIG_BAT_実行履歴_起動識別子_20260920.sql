-- MIGRATION-ID: bat-execution-process-run-id
-- ============================================================================
-- 移行: BAT_バッチ実行履歴情報 に「起動識別子」を追加する（再起動の復旧の境界）
-- 対象DB: study21 (PostgreSQL)
-- 冪等: ADD COLUMN IF NOT EXISTS / CREATE INDEX IF NOT EXISTS
-- ----------------------------------------------------------------------------
-- なぜ必要か:
--   再起動の復旧は「**前のプロセスが残した実行**」だけを扱わなければならない。
--   これを「起動時に読んだ最大の実行ID より古い行」で判定すると、
--   ・最初の読み込みが失敗し、その間に現在のプロセスが実行を作った場合
--     → 再試行で読んだ最大ID がその実行を含み、**自分の実行を遺留と誤認する**
--   ・最大ID は読めたが遺留リストの読み込みが失敗した場合
--     → 境界が固定されず、再試行のたびに広がりうる
--   という穴がある（どちらも「二重実行または実行中の行を閉じる」事故になる）。
--
--   そこで**実行記録の帰属**を列で持つ: 実行記録を作ったプロセスの識別子を書き、
--   復旧は「現在のプロセスの識別子と違う行（NULL を含む）」だけを遺留として扱う。
--   アプリ側は MyBatis のインターセプタで**すべての挿入**にこの値を刻む
--   （自動スケジューラ・起動時バッチ・手動実行・復旧のやり直しのすべて）。
--
-- 既存行は NULL のまま（＝この列が無かった頃の行）。復旧は NULL を
-- 「前のプロセスの遺留」として扱う（互換規則）。データは変更しない。
-- 実行順序:
--   1) この移行（列を足すだけ。アプリはまだこの列を書かなくても動く）
--   2) 新しいアプリ（この列を書く版）を配備
--   ※ 逆順（先に配備）でも動く（列が無いと挿入が失敗するため、必ず移行が先）
-- ============================================================================

ALTER TABLE public."BAT_バッチ実行履歴情報"
    ADD COLUMN IF NOT EXISTS "起動識別子" VARCHAR(40) NULL;

COMMENT ON COLUMN public."BAT_バッチ実行履歴情報"."起動識別子" IS
    '実行記録を作ったプロセスの起動識別子。再起動の復旧は「現在と違う値（NULL を含む）」だけを遺留として扱う';

-- 復旧が「前のプロセスの遺留（未完了）」を引くための索引。
CREATE INDEX IF NOT EXISTS idx_bat_history_leftover
    ON public."BAT_バッチ実行履歴情報" ("状態", "起動識別子")
    WHERE "状態" IN ('QUEUED', 'RUNNING');
