-- ============================================================================
-- Study 2.0 -> 2.1  読書管理 移行（追補 2）: 言語と分類のジャンル化
-- 対象: study21.public."RED_書籍情報"."言語" / "RED_書籍分類情報" の分類名
-- ----------------------------------------------------------------------------
-- 背景（利用者の指示・2026-09-13）:
--   ・書籍編集画面に**言語**の選択（中国語 / 英語 / 日本語）を足す
--   ・分類は「英語」「中国語」のような言語を含めず、**ジャンルだけ**にする
--     （英語 小説 → 小説 / 英語 リーディング → 雑誌・ガイド / 中国語 → 削除）
--
-- 事前条件: `TBL_RED_書籍情報.sql` の追補（言語 列）を適用しておくこと。
--
-- 値の決め方（実データ 6 冊）:
--   言語: 2.0 の タグ に '中国語' がある本（射鵰英雄伝）は 中国語、それ以外は 英語。
--         日本語の本は 2.0 に無いので 0 件（列は用意してある）。
--   分類: 「英語 小説」→「小説」、「英語 リーディング」→「雑誌・ガイド」に改名し、
--         言語で分けていた 射鵰英雄伝（中国語の小説）と Raya and the Last Dragon
--         （英語の小説）を「小説」へ移す。旧「中国語」分類は削除する（本は消えない）。
--
-- 実行例:
--   psql -h 192.168.0.100 -p 54320 -U postgres -d study21 -v ON_ERROR_STOP=1 \
--        -f database/移行/MIG_RED_読書_言語_20260913.sql
--
-- 冪等性: 何度実行しても結果は同じ（旧名が無ければ UPDATE は 0 件、分類の削除も 0 件）。
--   分類名の付け替えは「小説」「雑誌・ガイド」が既にある場合は行わない（一意制約に当たらない）。
--
-- 対象DB: study21 (PostgreSQL)
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. 言語（タグ '中国語' の本だけ中国語。それ以外は英語）
-- ---------------------------------------------------------------------------
UPDATE public."RED_書籍情報"
   SET "言語" = CASE WHEN COALESCE("タグ", '') LIKE '%中国語%' THEN '中国語' ELSE '英語' END,
       "更新元コード" = 'MIGRATION'
 WHERE "登録元コード" = 'MIGRATION';

-- ---------------------------------------------------------------------------
-- 2. 分類名をジャンルだけにする
-- ---------------------------------------------------------------------------
-- 2-1. 英語 小説 → 小説（「小説」がまだ無いときだけ）
UPDATE public."RED_書籍分類情報"
   SET "分類名" = '小説', "更新元コード" = 'MIGRATION'
 WHERE "分類名" = '英語 小説'
   AND NOT EXISTS (SELECT 1 FROM public."RED_書籍分類情報" c2 WHERE c2."分類名" = '小説');

-- 2-2. 英語 リーディング → 雑誌・ガイド（同上）
UPDATE public."RED_書籍分類情報"
   SET "分類名" = '雑誌・ガイド', "更新元コード" = 'MIGRATION'
 WHERE "分類名" = '英語 リーディング'
   AND NOT EXISTS (SELECT 1 FROM public."RED_書籍分類情報" c2 WHERE c2."分類名" = '雑誌・ガイド');

-- 2-3. 言語で分けていた本をジャンルの棚へ移す
--      ・射鵰英雄伝（中国語の小説）／Raya and the Last Dragon（英語の小説）→ 小説
--      ・Lonely Planet China（英語の旅行ガイド）→ 雑誌・ガイド
UPDATE public."RED_書籍情報" b
   SET "分類ID" = (SELECT c."分類ID" FROM public."RED_書籍分類情報" c WHERE c."分類名" = '小説'),
       "更新元コード" = 'MIGRATION'
 WHERE b."書籍名" IN ('射鵰英雄伝', 'Raya and the Last Dragon')
   AND EXISTS (SELECT 1 FROM public."RED_書籍分類情報" c WHERE c."分類名" = '小説');

UPDATE public."RED_書籍情報" b
   SET "分類ID" = (SELECT c."分類ID" FROM public."RED_書籍分類情報" c WHERE c."分類名" = '雑誌・ガイド'),
       "更新元コード" = 'MIGRATION'
 WHERE b."書籍名" = 'Lonely Planet China'
   AND EXISTS (SELECT 1 FROM public."RED_書籍分類情報" c WHERE c."分類名" = '雑誌・ガイド');

-- 2-4. 旧「中国語」分類を削除する（本は消えない＝分類ID が NULL になるだけ。
--      2-3 で本は「小説」へ移してあるので、未分類にはならない）
DELETE FROM public."RED_書籍分類情報"
 WHERE "分類名" = '中国語'
   AND NOT EXISTS (SELECT 1 FROM public."RED_書籍情報" b WHERE b."分類ID" = "RED_書籍分類情報"."分類ID");

-- 分類の表示順を詰める（小説=1 / 雑誌・ガイド=2）
UPDATE public."RED_書籍分類情報" SET "表示順" = 1 WHERE "分類名" = '小説';
UPDATE public."RED_書籍分類情報" SET "表示順" = 2 WHERE "分類名" = '雑誌・ガイド';

-- 言語が入っていない行（移行以外で作られた行）を埋める
UPDATE public."RED_書籍情報" SET "言語" = '英語' WHERE "言語" IS NULL;

-- ---------------------------------------------------------------------------
-- 3. 結果確認
-- ---------------------------------------------------------------------------
\echo '--- 分類ごとの冊数'
SELECT c."表示順", c."分類名", count(b."書籍ID") AS 冊数
  FROM public."RED_書籍分類情報" c
  LEFT JOIN public."RED_書籍情報" b ON b."分類ID" = c."分類ID"
 GROUP BY c."表示順", c."分類名"
 ORDER BY c."表示順";
\echo '--- 言語ごとの冊数'
SELECT "言語", count(*) AS 冊数 FROM public."RED_書籍情報" GROUP BY "言語" ORDER BY "言語";
\echo '--- 書籍ごとの 言語 と 分類'
SELECT b."書籍名", b."言語", COALESCE(c."分類名", '(未分類)') AS 分類, b."タグ"
  FROM public."RED_書籍情報" b
  LEFT JOIN public."RED_書籍分類情報" c ON c."分類ID" = b."分類ID"
 ORDER BY b."書籍ID";

COMMIT;
