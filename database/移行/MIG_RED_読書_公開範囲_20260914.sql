-- ============================================================================
-- Study 2.1  読書管理 移行: 公開範囲（全体書籍 / 家庭の書籍）と【自分の本棚】
-- ----------------------------------------------------------------------------
-- 目的（2026-09-14 の決定）:
--   1. いままでの「家族で共有する 1 つの本棚」（`RED_書籍情報` の全行）を
--      **全体書籍（`公開範囲コード='GLOBAL'`）** として引き継ぐ。
--      `登録元コード` では分けない（`MIGRATION` の 6 冊も、画面から登録済みの
--      `APP` の本も**全部が全体書籍**）。＝ 利用者の見た目は変わらない。
--   2. `RED_自分の本棚情報` には**何も入れない**。移行直後は全アカウントの
--      【自分の本棚】が空になり、画面は空の案内
--      「まだ本がありません。図書館から本を追加してください。」を出す。
--      利用者が【図書館】の【本棚に入れる】で 1 冊ずつ入れる。
--   3. 分類（棚）は第 1 版では全家庭共通のまま（`所有家族学生ID = NULL`）。
--
-- 移行後の登録は 2 種類になる:
--   * 管理者が登録した本 → `GLOBAL`（誰の本棚にも入らない。各自が【図書館】から入れる）
--   * 保護者が登録した本 → `FAMILY` ＋ `所有家族学生ID`（自家庭）＋
--     **登録した本人の本棚にだけ** 1 行（家庭の他の人は【図書館】から入れる）
--   * 新しく登録した家庭の本棚も**空**から始まる（この移行と同じ扱い）
--
-- 事前条件（先に実行しておくこと。どちらも冪等）:
--   1. database/読書管理/TBL_RED_書籍情報.sql                （公開範囲コード / 所有家族学生ID の追補）
--   2. database/読書管理/TBL_RED_自分の本棚情報.sql           （新規テーブル）
--   3. database/読書管理/TBL_RED_書籍分類情報.sql             （所有家族学生ID の追補）
--   4. MIG_RED_読書_20260913.sql / MIG_RED_読書_分類_20260913.sql / MIG_RED_読書_言語_20260913.sql 済み
--
-- 実行例:
--   psql -h 192.168.0.100 -p 54320 -U postgres -d study21 -v ON_ERROR_STOP=1 \
--        -f database/移行/MIG_RED_読書_公開範囲_20260914.sql
--
-- 冪等性（**再実行しても家庭の書籍を壊さない**ことが最優先）:
--   * 書籍の補正は `WHERE "公開範囲コード" IS NULL` の行だけを GLOBAL にする。
--     DDL 追補（TBL_RED_書籍情報.sql）を先に当てていれば、この時点で既存行は
--     すでに全部 GLOBAL なので 0 件更新になる。
--     **`FAMILY` の行は絶対に触らない**（この機能で保護者が登録した家庭の書籍を、
--     移行の再実行が全体公開にしてしまうのを防ぐ）。
--   * 本棚には**何も入れない**ので、何度実行しても件数は増えない。
--   * 分類は触らない（家庭ごとの分類はアプリが作り、移行では作らない）。
--
-- ロールバック手順（この機能を戻すとき）:
--   BEGIN;
--     -- 1. 家庭の書籍を「全体書籍」に戻す（アプリからの登録分も全部 GLOBAL になる）
--     UPDATE public."RED_書籍情報"
--        SET "公開範囲コード" = 'GLOBAL', "所有家族学生ID" = NULL;
--     -- 2. 本棚を捨てる（列・制約は残してよい）
--     DROP TABLE IF EXISTS public."RED_自分の本棚情報";
--     -- 3. 分類の所有家族を戻す（家庭ごとの分類は全体の分類になる。同名が衝突するときは先に改名）
--     UPDATE public."RED_書籍分類情報" SET "所有家族学生ID" = NULL;
--   COMMIT;
--   ※ `RED_書籍情報` の列（公開範囲コード / 所有家族学生ID）は残してよい
--     （残す場合は既定値 FAMILY のままでも、アプリが常に明示するので害はない）。
--
-- 対象DB: study21 (PostgreSQL)
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. 既存の全書籍 → 全体書籍（GLOBAL / 所有家族学生ID = NULL）
--    公開範囲コード がまだ決まっていない（NULL の）行だけを GLOBAL に寄せる。
--    DDL 追補を先に当てていれば、この時点で既存行は全部 GLOBAL なので 0 件。
--    FAMILY の行は条件に入れない（再実行で家庭の書籍を全体公開にしないため）。
-- ---------------------------------------------------------------------------
UPDATE public."RED_書籍情報"
   SET "公開範囲コード" = 'GLOBAL',
       "所有家族学生ID" = NULL
 WHERE "公開範囲コード" IS NULL;

-- 想定外の値（GLOBAL / FAMILY 以外）が入っていたら、黙って直さずに止める
DO $$
DECLARE
    v_bad INTEGER;
BEGIN
    SELECT count(*) INTO v_bad
      FROM public."RED_書籍情報"
     WHERE "公開範囲コード" NOT IN ('GLOBAL', 'FAMILY');
    IF v_bad > 0 THEN
        RAISE EXCEPTION '公開範囲コード に想定外の値が % 件あります。TBL_RED_書籍情報.sql の追補を確認してください。', v_bad;
    END IF;
END $$;

-- ---------------------------------------------------------------------------
-- 2. 【自分の本棚】には何も入れない（決定 2）
--    既存アカウントへ一括投入しない。移行直後は全員の本棚が空になる。
--    ＝ ここに INSERT は書かない（あとで「初期投入」を足さないこと）。
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- 3. 分類は全家庭共通のまま（所有家族学生ID = NULL）
--    既存 2 件（小説 / 雑誌・ガイド）は列を足した時点で NULL になっている。
--    ここでは**何も更新しない**（あとから家庭ごとに作った分類を壊さないため）。
--    想定外に家庭の分類が入っていたら知らせるだけにする。
-- ---------------------------------------------------------------------------
DO $$
DECLARE
    v_family INTEGER;
BEGIN
    SELECT count(*) INTO v_family
      FROM public."RED_書籍分類情報"
     WHERE "所有家族学生ID" IS NOT NULL;
    IF v_family > 0 THEN
        RAISE NOTICE '家庭ごとの分類が % 件あります（この移行では触りません）。', v_family;
    END IF;
END $$;

-- ---------------------------------------------------------------------------
-- 3.5 旧名の空分類の後始末
--   `MIG_RED_読書_分類_20260913.sql` は分類の初期値（英語 小説 / 英語 リーディング /
--   中国語）を入れる移行で、そのあと `MIG_RED_読書_言語_20260913.sql` が
--   小説 / 雑誌・ガイド に改名している。**先の移行を再実行すると、改名前の名前の分類が
--   復活する**（一意制約が「分類名」から「(所有家族学生ID, 分類名)」に変わったため、
--   `ON CONFLICT ("分類名")` では止められない。この移行で `WHERE NOT EXISTS` に直した）。
--   ここでは**本が 1 冊も付いていない旧名の分類だけ**を消す（利用者が作った分類・
--   本が付いている分類・家庭の分類には触らない）。
-- ---------------------------------------------------------------------------
DELETE FROM public."RED_書籍分類情報" c
 WHERE c."所有家族学生ID" IS NULL
   AND c."登録元コード" = 'MIGRATION'
   AND c."分類名" IN ('英語 小説', '英語 リーディング', '中国語')
   AND NOT EXISTS (SELECT 1 FROM public."RED_書籍情報" b WHERE b."分類ID" = c."分類ID");

-- ---------------------------------------------------------------------------
-- 4. 結果確認
-- ---------------------------------------------------------------------------
\echo '--- 書籍の公開範囲（GLOBAL=6 が期待値）'
SELECT "公開範囲コード", count(*) AS 冊数
  FROM public."RED_書籍情報"
 GROUP BY "公開範囲コード"
 ORDER BY 1;
\echo '--- 自分の本棚（0 が期待値。移行では初期投入しない）'
SELECT count(*) AS 本棚の行数 FROM public."RED_自分の本棚情報";
\echo '--- 家庭の書籍（0 が期待値。移行直後は全部が全体書籍）'
SELECT count(*) AS 家庭の冊数
  FROM public."RED_書籍情報"
 WHERE "公開範囲コード" = 'FAMILY';
\echo '--- 分類（2 件・すべて全体の分類が期待値）'
SELECT count(*) AS 分類数, count("所有家族学生ID") AS 家庭の分類数
  FROM public."RED_書籍分類情報";
\echo '--- その他のデータは無傷（記録・標記・ファイル。移行では触らない）'
SELECT (SELECT count(*) FROM public."RED_読書記録情報") AS 読書記録,
       (SELECT count(*) FROM public."RED_標記情報")     AS 標記,
       (SELECT count(*) FROM public."RED_書籍ファイル情報") AS ファイル;

COMMIT;
