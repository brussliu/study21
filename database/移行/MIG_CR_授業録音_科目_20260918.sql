-- ============================================================================
-- Study 2.1  移行: 授業録音に「科目」を独立した列で持つ
-- テーブル: CR_授業記録情報
-- ----------------------------------------------------------------------------
-- 背景: 科目（数学・英語など）は今まで**授業名に混ぜて**保存していた（例「数学 二次関数の復習」）。
--       一覧で科目を独立して出したい・絞り込みたいという利用者の指示で列を分ける。
--       既存の行は授業名のままにする（画面は科目が空なら何も出さない）。
--
-- 何度流しても同じ（ADD COLUMN IF NOT EXISTS / COMMENT は上書き）。
-- 対象DB: study21 (PostgreSQL)
-- ============================================================================

ALTER TABLE public."CR_授業記録情報"
    ADD COLUMN IF NOT EXISTS "科目" VARCHAR(40) NULL;

COMMENT ON COLUMN public."CR_授業記録情報"."科目" IS
    '科目（数学・英語など。授業名とは別に持つ。未設定は NULL）';

